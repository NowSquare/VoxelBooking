<?php

declare(strict_types=1);

// Reads registry definitions only. It never boots the application or connects to a database.
require dirname(__DIR__) . '/vendor/autoload.php';
App\Engine\Locale::init(dirname(__DIR__));
App\Engine\Locale::setLocale('en');

$destination = $argv[1] ?? null;
if (!$destination || !is_dir($destination)) {
    fwrite(STDERR, "Usage: php scripts/export-agent-docs.php <existing-output-directory>\n");
    exit(1);
}
$definitions = App\Agent\Operations::registry()->all();
$generator = new App\Agent\Mcp\ContractGenerator();
$writeJson = static function (string $name, array $value) use ($destination): void {
    file_put_contents($destination . '/' . $name, json_encode($value, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . "\n");
};
$writeJson('openapi.json', $generator->openApi($definitions, 'https://booking.example/api/agent/v2', '2'));
$writeJson('tools.json', $generator->tools($definitions));
$lines = [
    '<!-- Generated by the application scripts/export-agent-docs.php. Do not edit rows by hand. -->',
    '',
    '| Operation | Actor and scopes | HTTP route | Change and effects | Guide |',
    '| --- | --- | --- | --- | --- |',
];
foreach ($definitions as $definition) {
    $scopes = $definition->requiredScopes ? implode(', ', array_map(static fn ($scope) => '`' . $scope . '`', $definition->requiredScopes)) : 'No additional scope';
    $effect = $definition->readOnly ? 'Read' : ($definition->confirmationPolicy === 'none' ? 'Write' : 'Preview, review, commit');
    if ($definition->sideEffects) {
        $effect .= '; ' . implode(', ', $definition->sideEffects);
    }
    $page = App\Agent\Mcp\Documentation::page($definition->documentationPage);
    $path = preg_replace('#^/api/agent/v2(?=/|$)#', '', $definition->httpPath);
    $lines[] = '| `' . $definition->operationId . '` | ' . $definition->actorPolicy . '; ' . $scopes . ' | `' . $definition->httpMethod . ' ' . $path . '` | ' . $effect . ' | [Task guide](/docs/agent-api/' . $page . ') |';
}
file_put_contents($destination . '/operation-table.md', implode("\n", $lines) . "\n");
fwrite(STDOUT, 'Exported ' . count($definitions) . " operation definitions without database access.\n");
